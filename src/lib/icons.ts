/**
 * Drawings the icon admin's Save all writes, one file per role at
 * `src/assets/icons/roles/<role>.svg`. A role's file wins over its default.
 */
const SAVED = import.meta.glob<string>("@/assets/icons/roles/*.svg", {
  query: "?raw",
  import: "default",
  eager: true,
});

/** Glob key of the file Save all writes for `role`. */
export const savedKey = (role: string) => `/src/assets/icons/roles/${role}.svg`;

/** `roles` with each drawing swapped for its entry in `saved`, when it has one. */
export function withSaved<T extends Record<string, { svg: string }>>(
  roles: T,
  saved: Record<string, string>,
): T {
  return Object.fromEntries(
    Object.entries(roles).map(([name, role]) => [
      name,
      { ...role, svg: saved[savedKey(name)] ?? role.svg },
    ]),
  ) as T;
}

/** Every icon by role: a meaning, its tier, and for an emblem the `art` role of its `-detail` pair. */
export const ROLES = withSaved(DEFAULT_ROLES, SAVED);
